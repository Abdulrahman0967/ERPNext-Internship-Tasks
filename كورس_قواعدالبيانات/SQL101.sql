-- 2. إنشاء الجداول
-- إنشاء جدول الطلاب
CREATE TABLE Students (
    id INT PRIMARY KEY,
    student_name VARCHAR(100),
    dob DATE,
    gender CHAR(1), -- M أو F
    enrollment_date DATE,
    email VARCHAR(100),
    grade_level INT, -- 1 إلى 6
    track VARCHAR(50), -- علمي أو انساني
    gpa DECIMAL(5,2) -- من 100
);

-- إنشاء جدول المعلمين
CREATE TABLE Teachers (
    id INT PRIMARY KEY,
    teacher_name VARCHAR(100),
    dob DATE,
    gender CHAR(1),
    email VARCHAR(100),
    office_number VARCHAR(20)
);

-- إنشاء جدول المواد
CREATE TABLE Subjects (
    id INT PRIMARY KEY,
    subject_name VARCHAR(100)
);

